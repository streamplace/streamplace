package api

import (
	"context"
	_ "embed"
	"encoding/json"
	"html/template"
	"net/http"
	"regexp"
	"sync"
	"time"

	"github.com/julienschmidt/httprouter"
	apierrors "stream.place/streamplace/pkg/errors"
	"stream.place/streamplace/pkg/log"
)

//go:embed desktop-return.html
var desktopReturnHTML string

var desktopReturnTemplate = template.Must(template.New("desktop-return").Parse(desktopReturnHTML))

func writeDesktopReturn(ctx context.Context, w http.ResponseWriter, title, message string) {
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	w.Header().Set("Cache-Control", "no-store")
	if err := desktopReturnTemplate.Execute(w, struct{ Title, Message string }{title, message}); err != nil {
		log.Error(ctx, "error writing desktop return page", "error", err)
	}
}

var desktopTokenPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{16,128}$`)

const desktopReturnTTL = 10 * time.Minute

// Bounds for the public return route: a few concurrent logins, OAuth fields only.
const (
	desktopReturnMaxPending  = 16
	desktopReturnMaxParamLen = 2048
)

var desktopReturnParams = []string{"code", "state", "iss", "error", "error_description"}

type desktopOAuthPending struct {
	params  map[string]string
	expires time.Time
}

var desktopOAuthStore = struct {
	sync.Mutex
	pending map[string]desktopOAuthPending
}{pending: map[string]desktopOAuthPending{}}

// HandleDesktopOAuthReturn receives the system browser's OAuth redirect on the
// local node. The desktop app polls HandleDesktopOAuthCallback for the result.
func (a *StreamplaceAPI) HandleDesktopOAuthReturn(ctx context.Context) httprouter.Handle {
	return func(w http.ResponseWriter, r *http.Request, params httprouter.Params) {
		token := params.ByName("token")
		if !desktopTokenPattern.MatchString(token) {
			apierrors.WriteHTTPBadRequest(w, "invalid login token", nil)
			return
		}
		query := r.URL.Query()
		if query.Get("code") == "" && query.Get("error") == "" {
			apierrors.WriteHTTPBadRequest(w, "missing OAuth response", nil)
			return
		}
		kept := map[string]string{}
		for _, key := range desktopReturnParams {
			if value := query.Get(key); value != "" {
				if len(value) > desktopReturnMaxParamLen {
					apierrors.WriteHTTPBadRequest(w, "OAuth response too large", nil)
					return
				}
				kept[key] = value
			}
		}
		now := time.Now()
		desktopOAuthStore.Lock()
		for key, pending := range desktopOAuthStore.pending {
			if now.After(pending.expires) {
				delete(desktopOAuthStore.pending, key)
			}
		}
		_, replacing := desktopOAuthStore.pending[token]
		if !replacing && len(desktopOAuthStore.pending) >= desktopReturnMaxPending {
			desktopOAuthStore.Unlock()
			apierrors.WriteHTTPTooManyRequests(w, "too many pending desktop logins")
			return
		}
		desktopOAuthStore.pending[token] = desktopOAuthPending{
			params:  kept,
			expires: now.Add(desktopReturnTTL),
		}
		desktopOAuthStore.Unlock()
		writeDesktopReturn(ctx, w, "You're logged in", "You can close this window and return to Streamplace Desktop.")
	}
}

// HandleDesktopOAuthCallback hands the pending OAuth response to the desktop
// app once. The token is a secret generated by the app and embedded in the
// redirect URI, so another local client can't claim it.
func (a *StreamplaceAPI) HandleDesktopOAuthCallback(ctx context.Context) httprouter.Handle {
	return func(w http.ResponseWriter, r *http.Request, params httprouter.Params) {
		token := params.ByName("token")
		if !desktopTokenPattern.MatchString(token) {
			apierrors.WriteHTTPBadRequest(w, "invalid login token", nil)
			return
		}
		desktopOAuthStore.Lock()
		pending, ok := desktopOAuthStore.pending[token]
		delete(desktopOAuthStore.pending, token)
		desktopOAuthStore.Unlock()
		if !ok || time.Now().After(pending.expires) {
			apierrors.WriteHTTPNotFound(w, "no pending desktop login", nil)
			return
		}
		out := pending.params
		w.Header().Set("Content-Type", "application/json")
		w.Header().Set("Cache-Control", "no-store")
		if err := json.NewEncoder(w).Encode(out); err != nil {
			log.Error(ctx, "error writing response", "error", err)
		}
	}
}
